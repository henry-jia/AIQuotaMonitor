/// <summary>
/// UI 多语言（简体中文 + English）。
/// 配置值："auto" 跟随系统（CurrentUICulture 为 zh 用中文，否则英文）/ "zh" / "en"。
/// </summary>
public static class I18n
{
    public const string LangAuto = "auto";
    public const string LangZh = "zh";
    public const string LangEn = "en";

    /// <summary>当前生效语言（"zh" / "en"）。</summary>
    public static string Current { get; private set; } = Resolve(null);

    /// <summary>生效语言变化时触发（各窗口据此刷新文案）。</summary>
    public static event Action? Changed;

    /// <summary>启动时按配置初始化（auto = 跟随系统），不触发 Changed。</summary>
    public static void Initialize(string? cfgLang) => Current = Resolve(cfgLang);

    /// <summary>切换语言配置；解析出的生效语言变化时触发 Changed。</summary>
    public static void Set(string? cfgLang)
    {
        var lang = Resolve(cfgLang);
        if (lang == Current) return;
        Current = lang;
        Changed?.Invoke();
    }

    private static string Resolve(string? cfgLang) => cfgLang switch
    {
        LangZh => LangZh,
        LangEn => LangEn,
        _ => CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "zh" ? LangZh : LangEn,
    };

    public static string T(string key) =>
        (Current == LangEn ? En : Zh).TryGetValue(key, out var s) ? s
        : Zh.TryGetValue(key, out s) ? s : key;

    public static string T(string key, params object[] args) => string.Format(T(key), args);

